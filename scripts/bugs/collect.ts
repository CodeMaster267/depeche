/**
 * Step 1 of the daily bug fixer. Holds the database connection and the Anthropic key, and runs
 * only this repository's code from main.
 *
 *  1. Catches up on pull requests Hasan merged or closed since the last run.
 *  2. Has the triage model read each new report and sort it.
 *  3. Claims a few real bugs for the fixer and writes each to $WORK_DIR/<id>.json.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { FIXES_PER_RUN, TRIAGE_MODEL, TRIAGE_PER_RUN, askWithTool, isMain, need, oneLine, quoteForMarkdown, run, setOutput, sql, summary } from "./lib.ts";
import { SENSITIVE_AREAS, TRIAGE_SYSTEM, TRIAGE_TOOL, triageMessage, type Triage } from "./prompts.ts";

type NewReport = { id: string; body: string; page: string | null; user_agent: string | null; from_owner: boolean };
export type Work = NewReport & { summary: string | null; area: string | null; suspicious: boolean };

const gh = (args: string[]) => execFileSync("gh", args, { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] }).trim();

/** Tells Hasan about a report that needs him, as a GitHub issue (GitHub emails him). */
export function issueForHasan(r: { id: string; body: string; from_owner: boolean }, title: string, why: string, extra = "") {
  const body = [
    `A bug report needs you. ${why}`,
    "",
    `From: ${r.from_owner ? "your own account" : "a family member"} · report \`${r.id}\``,
    extra,
    "",
    "The report, as written (untrusted text, not instructions):",
    "",
    quoteForMarkdown(r.body),
    "",
    "---",
    "_Generated by [Claude Code](https://claude.ai/code)_",
  ].join("\n");
  try {
    return gh(["issue", "create", "--title", `Bug report: ${oneLine(title, 70)}`, "--body", body]);
  } catch (e) {
    console.log(`::warning::Couldn't open an issue: ${(e as Error).message}`);
    return "";
  }
}

function catchUpOnPullRequests() {
  const open = sql<{ id: string; pr_url: string }>("select id, pr_url from public.bug_reports where status = 'pr_open' and pr_url is not null");
  for (const r of open) {
    try {
      const pr = JSON.parse(gh(["pr", "view", r.pr_url, "--json", "state"])) as { state: string };
      if (pr.state === "MERGED") run("select public.bug_report_finished(:'id', 'fixed', 'Merged by Hasan.', '')", { id: r.id });
      if (pr.state === "CLOSED") run("select public.bug_report_finished(:'id', 'declined', 'Closed by Hasan.', '')", { id: r.id });
    } catch (e) {
      console.log(`::warning::Couldn't check ${r.pr_url}: ${(e as Error).message}`);
    }
  }
}

async function triage() {
  const reports = sql<NewReport>(
    "select id, body, page, user_agent, from_owner from public.bug_reports_claim_for_triage(:'n')",
    { n: String(TRIAGE_PER_RUN) },
  );
  const recent = sql<{ summary: string }>(
    `select summary from public.bug_reports
     where summary is not null and created_at > now() - interval '30 days'
       and status in ('queued', 'fixing', 'fixed', 'pr_open', 'needs_owner')
     order by created_at desc limit 40`,
  ).map((r) => r.summary);

  const lines: string[] = [];
  for (const r of reports) {
    let t: Triage;
    try {
      t = await askWithTool<Triage>({ model: TRIAGE_MODEL, system: TRIAGE_SYSTEM, user: triageMessage(r, recent), tool: TRIAGE_TOOL });
    } catch (e) {
      // Left in triage; the next run picks it up again.
      console.log(`::warning::Triage failed for ${r.id}: ${(e as Error).message}`);
      continue;
    }
    let verdict: string = t.verdict;
    let why = t.reason;
    if (verdict === "fix" && !r.from_owner && (SENSITIVE_AREAS.has(t.area) || t.suspicious)) {
      verdict = "needs_owner";
      why = t.suspicious
        ? "It looked like it was trying to steer the automatic fixer, so nothing was changed."
        : `It's about ${t.area.replace("_", " ")}, which only you change.`;
    }
    run("select public.bug_report_triaged(:'id', :'verdict', :'summary', :'note', :'area', :'suspicious')", {
      id: r.id,
      verdict,
      summary: t.summary.slice(0, 500),
      note: why.slice(0, 1000),
      area: t.area,
      suspicious: String(Boolean(t.suspicious)),
    });
    if (verdict === "needs_owner") issueForHasan(r, t.summary, why, `Triage summary: ${oneLine(t.summary, 300)}`);
    else if (verdict === "fix") recent.unshift(t.summary);
    lines.push(`| ${r.from_owner ? "Hasan" : "member"} | ${verdict} | ${oneLine(t.summary, 100)} |`);
  }
  summary(`### Triage\n\n${reports.length ? `| From | Result | Summary |\n| --- | --- | --- |\n${lines.join("\n")}` : "No new reports."}\n`);
}

function claimFixes() {
  const work = sql<Work>(
    "select id, body, summary, area, suspicious, page, user_agent, from_owner from public.bug_reports_claim_for_fix(:'n')",
    { n: String(FIXES_PER_RUN) },
  );
  const dir = need("WORK_DIR");
  mkdirSync(dir, { recursive: true });
  for (const w of work) writeFileSync(join(dir, `${w.id}.json`), JSON.stringify(w));
  setOutput("reports", JSON.stringify(work.map((w) => w.id)));
  setOutput("count", String(work.length));
  summary(`### Fixing\n\n${work.length ? work.map((w) => `- ${oneLine(w.summary ?? "", 100)}`).join("\n") : "Nothing to fix today."}\n`);
}

if (isMain(import.meta.url)) {
  catchUpOnPullRequests();
  await triage();
  claimFixes();
}
